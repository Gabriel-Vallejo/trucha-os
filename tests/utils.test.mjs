// Pruebas de la lógica de "Utilidades Trucha" (calculadora y conversiones).  node tests/utils.test.mjs
import fs from "node:fs";
import assert from "node:assert/strict";
const src = fs.readFileSync(new URL("../dotfiles/.config/dms/plugins/truchaUtils/utils.js", import.meta.url), "utf8").replace(".pragma library", "");
const U = new Function(src + "; return { calc, fmtNum, b64enc, b64dec, hexenc, hexdec, rot13, binenc, bindec, hexColor, results };")();
const eq = (a, b) => assert.deepEqual(a, b);
eq(U.fmtNum(U.calc("2+2*3")), "8");
eq(U.fmtNum(U.calc("0.1+0.2")), "0.3");
eq(U.calc("2^3^2"), 512);
eq(U.calc("-2^2"), -4);
eq(U.calc("(1+2)*3"), 9);
eq(U.calc("5!"), 120);
eq(U.calc("sqrt(16)+max(1,7)"), 11);
eq(U.calc("0xff+0b11"), 258);
eq(U.calc("3,5*2"), 7);
eq(U.calc("1/0"), null);
eq(U.calc("alert(1)"), null);
eq(U.calc("2+"), null);
eq(U.calc("hola"), null);
eq(U.b64enc("hola"), "aG9sYQ==");
eq(U.b64enc("ñ鱒"), Buffer.from("ñ鱒").toString("base64"));
eq(U.b64dec("aG9sYQ=="), "hola");
eq(U.b64dec("8J+QnyB0cnVjaGE="), "🐟 trucha");
eq(U.hexenc("AB"), "4142");
eq(U.hexdec("0x41 42"), "AB");
eq(U.hexdec("ff00"), null);
eq(U.rot13("Hola Zz"), "Ubyn Mm");
eq(U.bindec(U.binenc("hi")), "hi");
eq(U.hexColor("#e5383b").rgb, "rgb(229, 56, 59)");
eq(U.hexColor("#fff").hsl, "hsl(0, 0%, 100%)");
eq(U.hexColor("abc"), null);
const r = (q) => U.results(q, Date.UTC(2026, 9, 30));
eq(r("2+2")[0].value, "4");
eq(r("255").map(x => x.value).slice(0, 4), ["255", "0xff", "0b11111111", "0o377"]);
eq(r("b64 hola")[0].value, "aG9sYQ==");
eq(r("b64d !!!")[0].name, "No se puede convertir");
eq(r("ts 0")[0].comment, "Base64"); // "ts 0" no es timestamp (9-13 cifras): se trata como texto
eq(r("ts 1700000000")[1].value, "2023-11-14T22:13:20.000Z");
eq(r("ts")[0].value, String(Date.UTC(2026, 9, 30) / 1000));
eq(r("flag{x}").map(x => x.comment), ["Base64", "Hex", "ROT13", "URL"]);
eq(r("ZmxhZ3t4fQ==")[0].value, "flag{x}");
eq(r(""), []);
console.log("OK: todas las pruebas pasan");
